"""Markdown tables of all Fortran runs (tests/data/fortran/*.toml).

    uv run tools/fortran_tables.py      -> writes docs/fortran-paper-runs.tables.md
"""

import contextlib
import math
import tomllib
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs/fortran-paper-runs.tables.md"


def main():
    with open(OUT, "w") as fh, contextlib.redirect_stdout(fh):
        print("# Fortran ROWMAP runs — all tables\n")
        print("Generated by `uv run tools/fortran_tables.py` from `tests/data/fortran/*.toml`. "
              "Do not edit by hand.\n")
        tables()
    print(f"wrote {OUT.relative_to(ROOT)}")


def tables():
    rows = defaultdict(list)
    for f in sorted((ROOT / "tests/data/fortran").glob("*.toml")):
        with open(f, "rb") as fh:
            d = tomllib.load(fh)
        r, s = d["run"], d["stats"]
        rows[(r["problem"], r["m"], r["n"], r["method"], r["sft"])].append((r["rtol"], r["idid"], s))
    order = ["bruss", "heat", "nilidi", "food", "food3", "vdpl", "difkon", "diffu2"]
    for key in sorted(rows, key=lambda k: (order.index(k[0]), -k[1], k[3], k[4])):
        prob, m, n, meth, sft = key
        head = f"### {prob.upper()} m={m} (n={n}), {meth.upper()}"
        if sft:
            head += f", sft={sft}"
        print(head + "\n")
        print("| tol | idid | ERR | lg ERR | nstep | nfeval | CPU [s] |")
        print("|---|---|---|---|---|---|---|")
        for tol, idid, s in sorted(rows[key], reverse=True):
            e = s["err"]
            lg = f"{math.log10(e):.2f}" if math.isfinite(e) and e > 0 else "–"
            es = f"{e:.2e}" if math.isfinite(e) else "–"
            print(f"| {tol:.0e} | {idid} | {es} | {lg} | {s['nstep']} | {s['nfeval']} | {s['cpu_time']:.3f} |")
        print()


if __name__ == "__main__":
    main()
